#!/usr/bin/env python3
"""Sync data/workforce.js from the DOE-collector SQLite (monthly DOE dashboard scrape).

Source: DOE dashboard "ประมาณการแรงงานไทยที่คาดว่ายังทำงานอยู่ต่างประเทศ" (กองบริหารแรงงานไทยไปต่างประเทศ),
scraped monthly by the collectors-manager cron `doe-collector-monthly` into DOE-collector/doe_labour_monitoring.db.

Usage: sync-workforce.py [--db PATH] [--check]
  exit 0 = file written (or unchanged) · 10 = changed (with --check: would change) · 2 = error
Stdlib only. Never invents a number: a site country missing from the snapshot is an error, not a zero.
"""
import argparse, json, sqlite3, sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "data" / "workforce.js"
DB = Path.home() / "Documents/Personal-Project/DOE-collector/doe_labour_monitoring.db"
SOURCE = "https://datastudio.google.com/u/0/reporting/89607282-a4c6-4a0c-b6e9-a2934c16d885/page/p_rawnmuf5lc"
# site country code -> the dashboard's own country name
NAMES = {"TW": "ไต้หวัน", "IL": "อิสราเอล", "KR": "เกาหลีใต้", "JP": "ญี่ปุ่น", "AE": "ยูเออี", "RO": "โรมาเนีย", "LT": "ลิทัวเนีย"}
MIN_TOTAL = 100_000  # a half-crawled snapshot (seen 2026-09) is smaller than this; skip it


def snapshots(con):
    return con.execute(
        "SELECT snapshot_id, substr(scraped_at,1,10), total_workers, total_countries FROM snapshots "
        "WHERE total_workers >= ? ORDER BY scraped_at DESC", (MIN_TOTAL,)).fetchall()


def counts(con, sid):
    return dict(con.execute("SELECT country, worker_count FROM monthly_country_stats WHERE snapshot_id=?", (sid,)))


def build(db):
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    snaps = snapshots(con)
    if not snaps:
        raise SystemExit("no complete snapshot in DB")
    sid, date, total, ncountries = snaps[0]
    cur = counts(con, sid)
    if sum(cur.values()) != total:
        raise SystemExit(f"{sid}: country rows sum {sum(cur.values())} != snapshot total {total}")
    prev_sid, prev_date = (snaps[1][0], snaps[1][1]) if len(snaps) > 1 else (None, None)
    prev = counts(con, prev_sid) if prev_sid else {}
    ranked = sorted(cur.values(), reverse=True)
    by = {}
    for code, name in NAMES.items():
        if name not in cur:
            raise SystemExit(f"{sid}: '{name}' ({code}) not in snapshot — dashboard renamed it?")
        n = cur[name]
        by[code] = {"count": n, "prev": prev.get(name), "rank": ranked.index(n) + 1}
    return {"date": date, "prevDate": prev_date, "total": total, "countries": len(cur), "source": SOURCE,
            "snapshot": sid, "byCountry": by}


def render(d):
    body = json.dumps(d, ensure_ascii=False, indent=2)
    return (
        "// GENERATED by scripts/sync-workforce.py from DOE-collector (monthly scrape of the DOE dashboard\n"
        "// \"ประมาณการแรงงานไทยที่คาดว่ายังทำงานอยู่ต่างประเทศ\"). Do not hand-edit; re-run the script.\n"
        "// date = day the dashboard was scraped; rank = among all destination countries in that snapshot.\n"
        f"export const WORKFORCE = {body};\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=str(DB))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        text = render(build(Path(a.db)))
    except SystemExit as e:
        print(f"ERROR {e}", file=sys.stderr)
        return 2
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if text == old:
        print("UNCHANGED", OUT.name)
        return 0
    if not a.check:
        OUT.write_text(text, encoding="utf-8")
    print(("WOULD CHANGE" if a.check else "WROTE"), OUT.name)
    return 10


if __name__ == "__main__":
    sys.exit(main())
